#include <pthread.h>
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <time.h>

//-----------------------------------------------------------------------------
//      __   ___  ___         ___  __
//     |  \ |__  |__  | |\ | |__  /__`
//     |__/ |___ |    | | \| |___ .__/
//-----------------------------------------------------------------------------
long long N = 10000000;

//-----------------------------------------------------------------------------
//     ___      __   ___  __   ___  ___  __
//      |  \ / |__) |__  |  \ |__  |__  /__`
//      |   |  |    |___ |__/ |___ |    .__/
//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
//                __          __        ___  __
//     \  /  /\  |__) |  /\  |__) |    |__  /__`
//      \/  /~~\ |  \ | /~~\ |__/ |___ |___ .__/
//-----------------------------------------------------------------------------

//-----------------------------------------------------------------------------
//      __   __   __  ___  __  ___      __   ___  __
//     |__) |__) /  \  |  /  \  |  \ / |__) |__  /__`
//     |    |  \ \__/  |  \__/  |   |  |    |___ .__/
//-----------------------------------------------------------------------------
static __int128_t sum_range(long long lo, long long hi);
static void print_int128(__int128_t n);

//-----------------------------------------------------------------------------
//      __        __          __
//     |__) |  | |__) |    | /  `
//     |    \__/ |__/ |___ | \__,
//
//-----------------------------------------------------------------------------
//=============================================================================
int main(int argc, char *argv[])
{
    // Initialize time variables
    struct timespec t_start, t_end;
    double total_work_time;

    // Get timestamp
    clock_gettime(CLOCK_MONOTONIC, &t_start);
    // Handle command line inputs
    if (argc >= 2)
    {
        N = atoll(argv[1]);
    }
    __int128_t total_sum = 0;

    for (long long i = 0; i < N; i++)
    {
        total_sum = total_sum + i;
    }
    // Grab timestamp
    clock_gettime(CLOCK_MONOTONIC, &t_end);

    // Calculate work time
    total_work_time = ((t_end.tv_sec - t_start.tv_sec) * 1e9) + (t_end.tv_nsec - t_start.tv_nsec);

    // Return success
    printf("Total Sum: ");
    print_int128(total_sum);
    printf("\n");
    printf("Range: 0 - %lld\nTotal Time: %f (ns) or %f (s)\n", N, total_work_time, total_work_time / 1e9);
    return 0;
}

//-----------------------------------------------------------------------------
//      __   __              ___  ___
//     |__) |__) | \  /  /\   |  |__
//     |    |  \ |  \/  /~~\  |  |___
//
//-----------------------------------------------------------------------------
//=============================================================================

static __int128_t sum_range(long long lo, long long hi)
{
    // Calculate sum for the task
    __uint128_t sum = 0;
    for (long long i = lo; i < hi; i++)
    {
        sum += i;
    }
    return sum;
}

//=============================================================================
static void print_int128(__int128_t n)
{
    // If negative print a negative sign
    if (n < 0)
    {
        printf("-");
        n = -n;
    }

    // If n is greater than 9
    if (n > 9)
        // Keep calling recursively to print each digit of the large sum
        print_int128(n / 10);

    // Print the digit as a char using an ASCII conversion
    printf("%c", (char)('0' + n % 10));
}

