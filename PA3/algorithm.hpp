enum AlgorithmType
{
    RANDt,
    FIFOt,
    LRUt,
    PERt
};

class Algorithm
{
public:
    virtual ~Algorithm() = default;
    virtual int run(PhysicalFrame physical_memory[32], PageTable page_table[5]) = 0;
    virtual AlgorithmType getType() = 0;
};
//-----------------------------------------------------------------------------
//                __          __        ___  __
//     \  /  /\  |__) |  /\  |__) |    |__  /__`
//      \/  /~~\ |  \ | /~~\ |__) |___ |___ .__/
